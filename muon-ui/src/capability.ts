const normalizePath = (path: string): string =>
  (path.split("?")[0] ?? "").replaceAll("\\", "/");

const createCapabilityId = (usedIds: Set<string>): string => {
  for (;;) {
    const id = `cap-${randomBytes(capabilityIdByteLength).toString("hex")}`;
    if (!usedIds.has(id)) {
      usedIds.add(id);
      return id;
    }
  }
};

const parseCapabilitySpecifier = (
  source: string,
): ParsedCapabilitySpecifier | undefined => {
  if (!moduleNamePattern.test(source)) {
    return undefined;
  }
  const separator = source.indexOf(":");
  const namespace = `${source.slice(0, separator)}.${source.slice(separator + 1)}`;
  return {
    moduleName: source,
    namespace,
  };
};

const escapeRegExp = (source: string): string =>
  source.replace(/[\\^$+?.()|[\]{}]/gu, "\\$&");

const globToRegExp = (glob: string, separator: string): RegExp => {
  let source = "^";
  for (let index = 0; index < glob.length; index += 1) {
    const current = glob[index] ?? "";
    const next = glob[index + 1];
    if (current === "*" && next === "*") {
      source += ".*";
      index += 1;
      continue;
    }
    if (current === "*") {
      source += `[^${escapeRegExp(separator)}]*`;
      continue;
    }
    source += escapeRegExp(current);
  }
  source += "$";
  return new RegExp(source, "u");
};

const isGlobMatch = (glob: string, value: string, separator: string): boolean =>
  globToRegExp(glob, separator).test(value);

const containsGlob = (value: string): boolean => value.includes("*");

const toRootRelativeImporter = (root: string, importer: string): string =>
  normalizePath(relative(root, importer));

const readPackageName = (packageJsonPath: string): string | undefined => {
  try {
    const parsed = JSON.parse(readFileSync(packageJsonPath, "utf8")) as unknown;
    return typeof parsed === "object" &&
      parsed !== null &&
      !Array.isArray(parsed) &&
      typeof (parsed as { name?: unknown }).name === "string"
      ? (parsed as { name: string }).name
      : undefined;
  } catch {
    return undefined;
  }
};

const getImporterPackageName = (
  root: string,
  importer: string,
): string | undefined => {
  const normalizedRoot = normalizePath(root);
  const rootPackageJsonPath = join(root, "package.json");
  let directory = dirname(normalizePath(importer));
  for (;;) {
    const packageJsonPath = join(directory, "package.json");
    if (
      packageJsonPath !== rootPackageJsonPath &&
      existsSync(packageJsonPath)
    ) {
      return readPackageName(packageJsonPath);
    }
    if (normalizePath(directory) === normalizedRoot) {
      return undefined;
    }
    const parent = dirname(directory);
    if (parent === directory) {
      return undefined;
    }
    directory = parent;
  }
};

const matchesCapabilityRuleImporter = (
  rule: MuonCapabilityImportOptions,
  root: string,
  importer: string,
): boolean => {
  const relativeImporter = toRootRelativeImporter(root, importer);
  const sourceMatched =
    rule.sources?.some((pattern) =>
      isGlobMatch(normalizePath(pattern), relativeImporter, "/"),
    ) ?? false;
  if (sourceMatched) {
    return true;
  }

  const packageName = getImporterPackageName(root, importer);
  return packageName === undefined
    ? false
    : (rule.packages?.includes(packageName) ?? false);
};

const hasNamespaceFunctionAllow = (
  namespace: string,
  allow: readonly string[],
): boolean =>
  allow.some((entry) => {
    if (entry.startsWith(`${namespace}.`)) {
      return true;
    }
    return isGlobMatch(entry, `${namespace}.placeholder`, ".");
  });

const getExactExportName = (
  namespace: string,
  functionPath: string,
): string | undefined => {
  const prefix = `${namespace}.`;
  if (!functionPath.startsWith(prefix)) {
    return undefined;
  }
  const name = functionPath.slice(prefix.length);
  if (!jsIdentifierPattern.test(name)) {
    return undefined;
  }
  return name;
};

const getExportedFunctions = (
  namespace: string,
  allow: readonly string[],
  functionPaths: readonly string[],
): [string, string][] => {
  const exportedFunctions = new Map<string, string>();
  const addExport = (functionPath: string): void => {
    const exportName = getExactExportName(namespace, functionPath);
    if (exportName !== undefined && !exportedFunctions.has(exportName)) {
      exportedFunctions.set(exportName, functionPath);
    }
  };

  for (const entry of allow) {
    if (!containsGlob(entry)) {
      addExport(entry);
      continue;
    }
    for (const functionPath of functionPaths) {
      if (isGlobMatch(entry, functionPath, ".")) {
        addExport(functionPath);
      }
    }
  }
  return Array.from(exportedFunctions.entries());
};

const createFunctionPathCatalog = (
  functionPaths: readonly string[] | undefined,
): readonly string[] => {
  const catalog: string[] = [];
  const seen = new Set<string>();
  for (const functionPath of [
    ...defaultMuonCapabilityFunctionPaths,
    ...(functionPaths ?? []),
  ]) {
    if (!seen.has(functionPath)) {
      seen.add(functionPath);
      catalog.push(functionPath);
    }
  }
  return catalog;
};

const createRuleRuntimeEntry = (
  rule: MuonCapabilityImportOptions,
  id: string,
): MuonCapabilityRuntimeEntry => ({
  id,
  allow: [...rule.allow],
});

const validateCapabilityRule = (rule: MuonCapabilityImportOptions): void => {
  if (
    (rule.sources === undefined || rule.sources.length === 0) &&
    (rule.packages === undefined || rule.packages.length === 0)
  ) {
    throw new Error(
      "muon capability import rule requires sources or packages.",
    );
  }
};

const createModuleVirtualId = (rule: ResolvedRule): string =>
  `${virtualModulePrefix}${rule.index}:${rule.moduleName}`;

const parseModuleVirtualId = (
  id: string,
): { index: number; moduleName: string } | undefined => {
  if (!id.startsWith(virtualModulePrefix)) {
    return undefined;
  }
  const payload = id.slice(virtualModulePrefix.length);
  const separator = payload.indexOf(":");
  if (separator <= 0) {
    return undefined;
  }
  const index = Number.parseInt(payload.slice(0, separator), 10);
  if (!Number.isInteger(index) || index < 0) {
    return undefined;
  }
  return {
    index,
    moduleName: payload.slice(separator + 1),
  };
};

