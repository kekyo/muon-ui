/**
 * Import-side capability rule for muon plugin virtual modules.
 */
export interface MuonCapabilityImportOptions {
  /**
   * Importer path globs relative to the bundler project root.
   */
  sources?: readonly string[];
  /**
   * NPM package names allowed to import the virtual module.
   */
  packages?: readonly string[];
  /**
   * Plugin function path globs allowed for matching importers.
   */
  allow: readonly string[];
  /**
   * Plugin entry name that supplied this rule.
   *
   * @internal
   */
  pluginName?: string;
}

/**
 * Capability import configuration shared by bundler integrations.
 */
export interface MuonCapabilityOptions {
  /**
   * Capability imports allowed by importer path.
   */
  imports?: readonly MuonCapabilityImportOptions[];
  /**
   * Known public plugin function paths available for wildcard export expansion.
   *
   * @remarks Exact `imports[].allow` entries do not require this catalog.
   * Wildcard entries are expanded against these paths only when generating
   * virtual module named exports; runtime permission policies keep the original
   * wildcard patterns.
   */
  functionPaths?: readonly string[];
}

/**
 * Runtime capability policy generated for muon-core.
 */
export interface MuonCapabilityRuntimeEntry {
  /**
   * Opaque capability id embedded into generated virtual modules.
   */
  id: string;
  /**
   * Plugin function path globs allowed for this capability.
   */
  allow: readonly string[];
}

/**
 * Runtime plugin entry generated for muon-core config overlays.
 */
export interface MuonRuntimePluginEntryConfig {
  /**
   * Plugin entry name.
   */
  name: string;
  /**
   * Optional 64-character hexadecimal SHA-256 digest of the final external
   * `.so` or `.dll` file bytes followed by the decoded `salt` bytes.
   *
   * @remarks Calculate this after all library post-processing, including
   * stripping and code signing. It is not supported for `internal`.
   */
  signature?: string;
  /**
   * Optional hex-encoded salt whose decoded bytes are appended when checking
   * the plugin signature.
   *
   * @remarks Required when `signature` is specified. It is not supported for
   * `internal`.
   */
  salt?: string;
  /**
   * Plugin-defined string key-value configuration entries.
   */
  config?: Readonly<Record<string, string>>;
  /**
   * Plugin function path globs allowed for this plugin entry.
   */
  allow: readonly string[];
}

